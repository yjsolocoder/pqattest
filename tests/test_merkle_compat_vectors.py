"""Frozen v1 compatibility regression vectors for Merkle W-OTS.

These tests pin the exact v1 wire bytes of :class:`MerklePublicKey`,
:class:`MerkleSignature` and the full :class:`MerkleSigner` checkpoint so
that a future change to *both* the encoder and the decoder cannot silently
break reading already-persisted state and continuing to sign with it. A
current-version self round-trip cannot catch that; byte-exact comparison
against stored vectors can.

The constants below are stable test data. They were generated once from
fully deterministic key inputs -- the public ``token_bytes=`` constructor
hook fed an increasing counter -- and are never regenerated at test time.
They contain no real-world secret: every private element is a padded
counter value. Samples exist for ``w in (4, 8)`` at ``height = 2`` (four
leaves), in three states each:

* initial (nothing signed): ``next_index == 0``, ``remaining == 4``;
* after exactly one message: ``next_index == 1``, ``remaining == 3``;
* all four leaves spent: ``next_index == 4``, ``remaining == 0``.

Only the public API is used; no private format constants serve as an
expected value.
"""

