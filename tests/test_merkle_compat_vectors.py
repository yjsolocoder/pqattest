class CheckpointRestoreFailureTest(unittest.TestCase):
    """Corruptions of a stored vector must raise ValueError, never a signer."""

    def setUp(self):
        # w=4 initial checkpoint; long enough to host every corruption.
        self.blob = bytearray(_b(W4_CHECKPOINT_INITIAL))

    def assert_rejected(self, blob):
        with self.assertRaises(ValueError):
            MerkleSigner.from_checkpoint(blob)

    def test_unknown_version_rejected(self):
        for version in (0, 2, 255):
            with self.subTest(version=version):
                bad = bytearray(self.blob)
                bad[8] = version
                self.assert_rejected(bytes(bad))

    def test_truncated_rejected(self):
        for cut in (0, 8, 20, 48, len(self.blob) - 33, len(self.blob) - 1):
            with self.subTest(cut=cut):
                self.assert_rejected(bytes(self.blob[:cut]))

    def test_trailing_data_rejected(self):
        self.assert_rejected(bytes(self.blob) + b"\x00")
        self.assert_rejected(bytes(self.blob) + b"trailing")

    def test_bad_checksum_rejected(self):
        bad = bytearray(self.blob)
        bad[-1] ^= 0x01
        self.assert_rejected(bytes(bad))

    def test_recomputed_checksum_with_matching_fields_still_validates(self):
        # Sanity pin: recomputing the checksum over an unaltered body must
        # keep the vector restorable, so the next test isolates the root
        # mismatch rather than failing on checksum logic.
        body = bytes(self.blob[:-32])
        fixed = body + hashlib.sha256(body).digest()
        signer = MerkleSigner.from_checkpoint(fixed)
        self.assertEqual(signer.next_index, 0)
        self.assertEqual(signer.remaining, 4)

    def test_root_mismatch_rejected_even_with_valid_checksum(self):
        # Flip a byte in the stored root field and repair the checksum: the
        # root rebuilt from the private keys then fails to match.
        bad = bytearray(self.blob)
        bad[17] ^= 0x01
        bad[-32:] = hashlib.sha256(bytes(bad[:-32])).digest()
        self.assert_rejected(bytes(bad))

    def test_private_key_tampering_rejected_even_with_valid_checksum(self):
        # Flip a private element and repair the checksum: root mismatch.
        bad = bytearray(self.blob)
        bad[60] ^= 0x01
        bad[-32:] = hashlib.sha256(bytes(bad[:-32])).digest()
        self.assert_rejected(bytes(bad))


class ExhaustedVectorTest(unittest.TestCase):
    """The stored exhausted state restores exhausted and cannot sign."""

    def test_exhausted_checkpoint_has_no_remaining_leaves(self):
        for w in (4, 8):
            with self.subTest(w=w):
                blob = _b(globals()[f"W{w}_CHECKPOINT_EXHAUSTED"])
                signer = MerkleSigner.from_checkpoint(blob)
                self.assertEqual(signer.next_index, LEAF_COUNT)
                self.assertEqual(signer.remaining, 0)

    def test_signing_after_exhaustion_raises_and_leaves_bytes_intact(self):
        for w in (4, 8):
            with self.subTest(w=w):
                blob = _b(globals()[f"W{w}_CHECKPOINT_EXHAUSTED"])
                snapshot_before = bytes(blob)
                signer = MerkleSigner.from_checkpoint(blob)
                with self.assertRaises(KeyExhaustedError):
                    signer.sign(b"a perfectly legal message")
                with self.assertRaises(KeyExhaustedError):
                    signer.sign("str messages are legal too")
                # The failed attempt neither moves state nor changes bytes.
                self.assertEqual(signer.next_index, LEAF_COUNT)
                self.assertEqual(signer.remaining, 0)
                self.assertEqual(signer.checkpoint(), snapshot_before)
                self.assertEqual(bytes(blob), snapshot_before)


