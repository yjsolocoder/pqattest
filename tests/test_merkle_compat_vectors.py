HEIGHT = 2
LEAF_COUNT = 1 << HEIGHT  # 4

# Deterministic key input, fed through the public token_bytes= hook:
# successive calls return 1, 2, 3, ... as 8-byte big-endian integers padded
# on the left to the requested size. Same inputs must always yield the same
# public key, checkpoint and signature bytes.
def counter_tokens(start=0):
    state = {"value": start}

    def token_bytes(size):
        state["value"] += 1
        return state["value"].to_bytes(8, "big").rjust(size, b"\x00")

    return token_bytes


def make_signer(w):
    return MerkleSigner(height=HEIGHT, w=w, token_bytes=counter_tokens(0))


# Fixed messages recorded alongside the samples.
FIRST_MESSAGE = b"compat: first message"
LEAF_MESSAGES = (
    FIRST_MESSAGE,
    b"compat: leaf 1",
    b"compat: leaf 2",
    b"compat: leaf 3",
)
# Signed when resuming from the one-message checkpoint -> must use leaf 1.
CONTINUED_MESSAGE = b"compat: continued at leaf one"
# Differs from FIRST_MESSAGE / CONTINUED_MESSAGE in a single byte.
TAMPERED_MESSAGE = b"compat: first MESSAGE"


def _b(value):
    return base64.b64decode("".join(value))


