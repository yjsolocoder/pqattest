class FixedVectorTest(unittest.TestCase):
    """Exact-byte pins: stored v1 blobs decode, and fresh encoding matches."""

    def _vector(self, w):
        prefix = f"W{w}"
        return {
            "public_key": _b(globals()[f"{prefix}_PUBLIC_KEY"]),
            "cp_initial": _b(globals()[f"{prefix}_CHECKPOINT_INITIAL"]),
            "cp_after_one": _b(globals()[f"{prefix}_CHECKPOINT_AFTER_ONE"]),
            "cp_exhausted": _b(globals()[f"{prefix}_CHECKPOINT_EXHAUSTED"]),
            "first_signature": _b(globals()[f"{prefix}_FIRST_SIGNATURE"]),
            "continued_signature": _b(
                globals()[f"{prefix}_CONTINUED_SIGNATURE"]
            ),
        }

    def test_public_key_vectors_decode_and_fields_match(self):
        for w in (4, 8):
            with self.subTest(w=w):
                vectors = self._vector(w)
                key = MerklePublicKey.from_bytes(vectors["public_key"])
                self.assertEqual(key.w, w)
                self.assertEqual(key.height, HEIGHT)
                self.assertEqual(key.leaf_count, LEAF_COUNT)
                # A signer built from the recorded key input has that key.
                self.assertEqual(make_signer(w).public_key, key)

    def test_public_key_encoding_matches_vector_byte_for_byte(self):
        for w in (4, 8):
            with self.subTest(w=w):
                vectors = self._vector(w)
                self.assertEqual(
                    make_signer(w).public_key.to_bytes(), vectors["public_key"]
                )
                # Re-encoding a decoded key must reproduce the stored bytes.
                decoded = MerklePublicKey.from_bytes(vectors["public_key"])
                self.assertEqual(decoded.to_bytes(), vectors["public_key"])

    def test_checkpoint_vectors_restore_with_expected_state(self):
        expectations = (
            ("cp_initial", 0, 4),
            ("cp_after_one", 1, 3),
            ("cp_exhausted", 4, 0),
        )
        for w in (4, 8):
            vectors = self._vector(w)
            public_key = MerklePublicKey.from_bytes(vectors["public_key"])
            for name, next_index, remaining in expectations:
                with self.subTest(w=w, state=name):
                    signer = MerkleSigner.from_checkpoint(vectors[name])
                    self.assertEqual(signer.public_key, public_key)
                    self.assertEqual(signer.next_index, next_index)
                    self.assertEqual(signer.remaining, remaining)

    def test_checkpoint_encoding_matches_vector_byte_for_byte(self):
        # Same deterministic key inputs and messages must reproduce each
        # stored checkpoint exactly -- not merely a current round-trip.
        for w in (4, 8):
            vectors = self._vector(w)
            with self.subTest(w=w, state="initial"):
                self.assertEqual(
                    make_signer(w).checkpoint(), vectors["cp_initial"]
                )
            with self.subTest(w=w, state="after_one"):
                signer = make_signer(w)
                signer.sign(FIRST_MESSAGE)
                self.assertEqual(signer.checkpoint(), vectors["cp_after_one"])
            with self.subTest(w=w, state="exhausted"):
                signer = make_signer(w)
                for message in LEAF_MESSAGES:
                    signer.sign(message)
                self.assertEqual(signer.checkpoint(), vectors["cp_exhausted"])

    def test_bytes_and_bytearray_checkpoints_restore_identically(self):
        for w in (4, 8):
            for name in ("cp_initial", "cp_after_one", "cp_exhausted"):
                with self.subTest(w=w, state=name):
                    blob = self._vector(w)[name]
                    from_bytes = MerkleSigner.from_checkpoint(blob)
                    from_bytearray = MerkleSigner.from_checkpoint(
                        bytearray(blob)
                    )
                    self.assertEqual(
                        from_bytearray.public_key, from_bytes.public_key
                    )
                    self.assertEqual(
                        from_bytearray.next_index, from_bytes.next_index
                    )
                    self.assertEqual(
                        from_bytearray.remaining, from_bytes.remaining
                    )
                    self.assertEqual(
                        from_bytearray.checkpoint(), from_bytes.checkpoint()
                    )

    def test_first_signature_vector_decodes_and_verifies(self):
        for w in (4, 8):
            with self.subTest(w=w):
                vectors = self._vector(w)
                public_key = MerklePublicKey.from_bytes(vectors["public_key"])
                signature = MerkleSignature.from_bytes(
                    vectors["first_signature"], public_key
                )
                self.assertEqual(signature.index, 0)
                self.assertTrue(
                    merkle_verify(FIRST_MESSAGE, signature, public_key)
                )
                self.assertFalse(
                    merkle_verify(TAMPERED_MESSAGE, signature, public_key)
                )

    def test_first_signature_encoding_matches_vector_byte_for_byte(self):
        for w in (4, 8):
            with self.subTest(w=w):
                vectors = self._vector(w)
                signer = make_signer(w)
                signature = signer.sign(FIRST_MESSAGE)
                self.assertEqual(signature.index, 0)
                self.assertEqual(
                    signature.to_bytes(signer.public_key),
                    vectors["first_signature"],
                )

    def test_resumed_signer_continues_at_leaf_one_and_matches_vector(self):
        for w in (4, 8):
            with self.subTest(w=w):
                vectors = self._vector(w)
                public_key = MerklePublicKey.from_bytes(vectors["public_key"])
                signer = MerkleSigner.from_checkpoint(vectors["cp_after_one"])
                self.assertEqual(signer.next_index, 1)
                signature = signer.sign(CONTINUED_MESSAGE)
                self.assertEqual(signature.index, 1)
                self.assertEqual(
                    signature.to_bytes(public_key),
                    vectors["continued_signature"],
                )
                # The stored continued signature decodes through the public
                # entry point and verifies for its message only.
                decoded = MerkleSignature.from_bytes(
                    vectors["continued_signature"], public_key
                )
                self.assertEqual(decoded.index, 1)
                self.assertTrue(
                    merkle_verify(CONTINUED_MESSAGE, decoded, public_key)
                )
                self.assertFalse(
                    merkle_verify(TAMPERED_MESSAGE, decoded, public_key)
                )
                # Resuming spent exactly one more leaf.
                self.assertEqual(signer.next_index, 2)
                self.assertEqual(signer.remaining, 2)


